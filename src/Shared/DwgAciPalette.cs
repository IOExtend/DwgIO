    /// <summary>RGB of an AutoCAD Color Index; index 0 and 256 resolve to white (index 7).</summary>
    public static (byte R, byte G, byte B) RgbOf(int index)
    {
        int stored = Rgb[index is > 0 and < 256 ? index : 7];
        return ((byte)(stored >> 16 & 0xFF), (byte)(stored >> 8 & 0xFF), (byte)(stored & 0xFF));
